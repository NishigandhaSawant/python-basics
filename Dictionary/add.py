my_dict = {
    "Fruies": ["Apple", "Banana", "Orange"],
    "category": ["Fruit", "Vegetable", "Dairy"],
}

print(my_dict)  # Output: {'Fruies': ['Apple', 'Banana', 'Orange'], 'category': ['Fruit', 'Vegetable', 'Dairy']}
my_dict['Price'] = [100, 200, 300]
print(my_dict)  # Output: {'Fruies': ['Apple', 'Banana', 'Orange'], 'category': ['Fruit', 'Vegetable', 'Dairy'], 'Price': [100, 200, 300]}